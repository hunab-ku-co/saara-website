// Generates responsive, multi-format derivatives from the originals in
// assets/originals/ into public/img/, plus a typed manifest the React <Photo>
// component consumes.
//
// Run with: npm run images
//
// Outputs are committed to the repo. That keeps `npm run typecheck` and CI
// working without an image step ordering dependency, and makes builds fast and
// reproducible. Re-run this script whenever an original changes.

import { mkdir, rm, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import sharp from 'sharp'

const SRC = 'assets/originals'
const OUT = 'public/img'
const MANIFEST = 'src/images.generated.ts'

// Widths are chosen from how each image is actually used in the layout, capped
// at the source resolution — upscaling is never useful, it only wastes bytes.
const IMAGES = [
  {
    name: 'saara-portrait',
    file: 'saara-portrait.jpg',
    widths: [360, 560, 760, 1000, 1418],
    alt: 'Saara Kiventoyry',
  },
  {
    name: 'saara-blue',
    file: 'saara-blue.jpg',
    widths: [640, 1024, 1440, 1920, 2400, 2787],
    alt: 'Saara Kiventoyry',
  },
]

// Quality settings tuned to preserve facial detail and skin tones. 4:4:4 chroma
// avoids the colour smearing that 4:2:0 causes around lips and eyes — it costs
// some bytes, but these are the photographs the whole site rests on.
const ENCODERS = [
  {
    ext: 'avif',
    type: 'image/avif',
    apply: (p) =>
      p.avif({ quality: 62, effort: 6, chromaSubsampling: '4:4:4' }),
  },
  {
    ext: 'webp',
    type: 'image/webp',
    apply: (p) => p.webp({ quality: 84, effort: 6, smartSubsample: true }),
  },
  {
    ext: 'jpg',
    type: 'image/jpeg',
    apply: (p) =>
      p.jpeg({ quality: 88, mozjpeg: true, chromaSubsampling: '4:4:4' }),
  },
]

await rm(OUT, { recursive: true, force: true })
await mkdir(OUT, { recursive: true })

const manifest = {}
let totalBytes = 0

for (const image of IMAGES) {
  const input = join(SRC, image.file)
  const meta = await sharp(input).metadata()
  const widths = image.widths.filter((w) => w <= meta.width)
  if (
    !widths.includes(meta.width) &&
    image.widths.some((w) => w > meta.width)
  ) {
    widths.push(meta.width)
  }

  const sources = {}
  for (const { ext, type, apply } of ENCODERS) {
    const entries = []
    for (const width of widths) {
      const file = `${image.name}-${width}.${ext}`
      // withMetadata() is deliberately NOT called: it would carry EXIF/XMP —
      // including any GPS and camera serials — into published files. The ICC
      // profile is normalised to sRGB instead, so colour still renders right.
      const info = await apply(
        sharp(input)
          .resize({ width, withoutEnlargement: true })
          .toColourspace('srgb'),
      ).toFile(join(OUT, file))

      entries.push({ width, url: `/img/${file}`, bytes: info.size })
      totalBytes += info.size
    }
    sources[ext] = { type, entries }
  }

  const aspect = meta.width / meta.height
  manifest[image.name] = {
    alt: image.alt,
    width: meta.width,
    height: meta.height,
    aspect: Number(aspect.toFixed(4)),
    sources,
  }

  const largest = widths[widths.length - 1]
  const sizeOf = (ext) =>
    (sources[ext].entries.at(-1).bytes / 1024).toFixed(0) + 'kB'
  console.log(
    `${image.name.padEnd(16)} ${meta.width}x${meta.height} -> ${widths.length} widths ` +
      `(max ${largest}: avif ${sizeOf('avif')}, webp ${sizeOf('webp')}, jpg ${sizeOf('jpg')})`,
  )
}

// Social preview card. Link unfurls matter a lot for a campaign, and the
// platforms that render them mostly still want a plain landscape JPEG.
const OG = { width: 1200, height: 630 }
const ogInfo = await sharp(join(SRC, 'saara-blue.jpg'))
  .resize({ ...OG, fit: 'cover', position: 'attention' })
  .jpeg({ quality: 86, mozjpeg: true })
  .toFile(join(OUT, 'og.jpg'))
console.log(
  `og.jpg           ${OG.width}x${OG.height} (${(ogInfo.size / 1024).toFixed(0)}kB)`,
)

const names = Object.keys(manifest)
  .map((n) => `'${n}'`)
  .join(' | ')

const ts = `// GENERATED by scripts/build-images.mjs — do not edit by hand.
// Re-run \`npm run images\` after changing anything in assets/originals/.

export type ImageSource = {
  type: string
  entries: { width: number; url: string; bytes: number }[]
}

export type GeneratedImage = {
  alt: string
  width: number
  height: number
  aspect: number
  sources: Record<string, ImageSource>
}

export type ImageName = ${names}

export const IMAGES: Record<ImageName, GeneratedImage> = ${JSON.stringify(manifest, null, 2)}
`

await writeFile(MANIFEST, ts)
console.log(
  `\nwrote ${MANIFEST} — ${(totalBytes / 1024 / 1024).toFixed(2)} MB total across all variants`,
)
